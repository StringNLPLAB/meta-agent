"""Own one trainer and the existing meta-agent supervisor; never restart either.

The config is generated by the outer coding agent. Run in the foreground by
default, or detach the same controller into a new POSIX session. This is a
process owner, not an installed scheduler or operating-system service.
"""
from __future__ import annotations

import argparse
import fcntl
import json
import math
import os
from pathlib import Path
import signal
import subprocess
import sys
import time


REPO = Path(__file__).resolve().parents[1]
SCRIPTS = REPO / ".agent/skills/meta-agent/scripts"
sys.path.insert(0, str(SCRIPTS))
from agent_backends import backend_from_args
from eau_paths import canonical_run
from supervise import Supervisor, atomic_json, parser as supervisor_parser, pid_start


FIELDS = {"version", "root", "run", "trainer_command", "contract", "supervisor_args",
          "trainer_timeout_seconds", "poll_seconds", "final_timeout_seconds", "failure_policy"}
PROTECTED = {"--root", "--run", "--contract", "--completion-file", "--once", "--adopt-settings",
             "--help", "-h"}


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def positive(value, name, maximum=None):
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or value <= 0:
        raise ValueError(f"{name} must be a finite positive number")
    if maximum is not None and value > maximum:
        raise ValueError(f"{name} must be at most {maximum}")
    return float(value)


def resolve(root, value):
    path = Path(value).expanduser()
    return (root / path if not path.is_absolute() else path).resolve()


def normalized_config(path):
    config = read_json(path)
    if not isinstance(config, dict) or set(config) - FIELDS:
        raise ValueError("Launch config must be an object with supported fields only")
    if type(config.get("version")) is not int or config["version"] != 1:
        raise ValueError("Launch config needs version: 1")
    if not isinstance(config.get("root"), str) or not config["root"].strip():
        raise ValueError("root must name the existing training checkout")
    root_value = Path(config["root"]).expanduser()
    root = (Path(path).resolve().parent / root_value if not root_value.is_absolute() else root_value).resolve()
    if not root.is_dir():
        raise ValueError("root must be an existing training checkout")
    os.environ["EAU_ROOT"] = str(root)
    run = canonical_run(config.get("run"))
    command = config.get("trainer_command")
    if not isinstance(command, list) or not command or not all(isinstance(x, str) and x for x in command):
        raise ValueError("trainer_command must be a nonempty array of literal arguments")
    flags = config.get("supervisor_args")
    if not isinstance(flags, list) or not all(isinstance(x, str) and x for x in flags):
        raise ValueError("supervisor_args must be an array of literal arguments")
    if any(flag.split("=", 1)[0] in PROTECTED for flag in flags):
        raise ValueError("runtime owns root/run/contract/completion-file/once/adopt-settings; do not pass them")
    contract = config.get("contract")
    # Reuse the existing contract rules instead of inventing another schema.
    holder = type("Contract", (), {"contract": contract})()
    Supervisor.validate_contract(holder)
    runtime_dir = root / "reports/runtime" / run
    args = [*flags, "--root", str(root), "--run", run,
            "--contract", str(runtime_dir / "contract.json"),
            "--completion-file", str(runtime_dir / "completion.json")]
    argument_parser = supervisor_parser()
    argument_parser.allow_abbrev = False
    try:
        parsed = argument_parser.parse_args(args)
    except SystemExit as error:
        raise ValueError("Invalid supervisor_args; inspect the supervisor argument error") from error
    backend_from_args(parsed)
    if parsed.max_calls is None or parsed.max_calls < 2:
        raise ValueError("supervisor_args need --max-calls >= 2 for discovery and final review")
    if parsed.every_steps is None and parsed.every_seconds is None:
        raise ValueError("supervisor_args need a step and/or time review cadence")
    # Constructor validation is also performed by the preflight, before a
    # trainer is launched. Parsing here resolves the exact planned log early.
    if config.get("failure_policy", "stop_owned_trainer") != "stop_owned_trainer":
        raise ValueError("failure_policy currently supports only stop_owned_trainer")
    result = {"version": 1, "root": str(root), "run": run, "trainer_command": command,
              "contract": contract, "supervisor_args": flags,
              "trainer_timeout_seconds": positive(config.get("trainer_timeout_seconds"), "trainer_timeout_seconds"),
              "poll_seconds": positive(config.get("poll_seconds", 0.2), "poll_seconds", 60),
              "final_timeout_seconds": positive(config.get("final_timeout_seconds", 120), "final_timeout_seconds"),
              "failure_policy": "stop_owned_trainer"}
    return result, runtime_dir, parsed, args


def check_fresh(config, directory, parsed):
    if directory.exists() or directory.is_symlink():
        raise ValueError(f"Runtime run already exists; use a new run identity: {directory}")
    supervision = Path(config["root"]) / "reports/supervision" / config["run"]
    if supervision.exists() or supervision.is_symlink():
        raise ValueError("Supervision records already exist; runtime never implicitly resumes or restarts training")
    value = Path(parsed.log).expanduser()
    log = value if value.is_absolute() else Path(config["root"]) / value
    resolved_log = log.resolve()
    if resolved_log.is_relative_to(directory) and resolved_log != directory / "trainer.stdout":
        raise ValueError("Training log collides with runtime records; only runtime's trainer.stdout is a valid log there")
    if resolved_log.is_relative_to(supervision):
        raise ValueError("Training log must not collide with supervisor records")
    if log.exists() or log.is_symlink():
        raise ValueError(f"Planned training log already exists: {log}")


def owned_identity(process):
    return {"pid": process.pid, "start_token": pid_start(process.pid), "process_group": process.pid}


def run_lock_held(directory):
    try:
        with (directory / "runtime.lock").open("r+") as guard:
            try:
                fcntl.flock(guard, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                return True
            fcntl.flock(guard, fcntl.LOCK_UN)
    except FileNotFoundError:
        pass
    return False


def stop_group(process, grace=8):
    """Signal only a process group created and retained by this invocation."""
    if process.poll() is not None:
        return
    try:
        os.killpg(process.pid, signal.SIGTERM)
    except ProcessLookupError:
        pass
    try:
        process.wait(timeout=grace)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        process.wait(timeout=3)


class Runtime:
    def __init__(self, config, directory, parsed, supervisor_args):
        self.config, self.directory = config, directory
        self.parsed, self.supervisor_args = parsed, supervisor_args
        self.root = Path(config["root"])
        self.supervision = self.root / "reports/supervision" / config["run"]
        self.children, self.handles = {}, []
        self.guard = None
        self.detached = False
        self.state = {"version": 1, "run": config["run"], "status": "initializing",
                      "owner": {"pid": os.getpid(), "start_token": pid_start(os.getpid()),
                                "running": True, "mode": "foreground",
                                "lifetime": "this runtime process; no service is installed"},
                      "started_at": time.time(), "children": {}, "trainer_returncode": None,
                      "supervisor_returncode": None, "supervision_status": None}

    def save(self, status=None, **fields):
        changed = status and status != self.state["status"]
        if status:
            self.state["status"] = status
        self.state.update(fields, updated_at=time.time())
        atomic_json(self.directory / "state.json", self.state)
        if changed:
            line = f"[RUNTIME] {self.config['run']}: {status}; state={self.directory / 'state.json'}"
            if not self.detached:
                with (self.directory / "runtime.stdout").open("a", encoding="utf-8") as output:
                    output.write(line + "\n")
            print(line, flush=True)

    def spawn(self, name, command):
        stdout = (self.directory / f"{name}.stdout").open("ab")
        stderr = (self.directory / f"{name}.stderr").open("ab")
        self.handles.extend((stdout, stderr))
        process = subprocess.Popen(command, cwd=self.root, stdin=subprocess.DEVNULL,
                                   stdout=stdout, stderr=stderr, start_new_session=True,
                                   pass_fds=(self.guard.fileno(),), env=dict(os.environ, EAU_ROOT=str(self.root)))
        self.children[name] = process
        self.state["children"][name] = {**owned_identity(process), "running": True, "command": command}
        self.save()
        return process

    def child_finished(self, name):
        process = self.children[name]
        if not self.state["children"][name]["running"]:
            return
        self.state["children"][name].update(running=False, returncode=process.returncode, finished_at=time.time())
        if name == "trainer":
            self.state["children"][name]["returncode_source"] = "managed wrapper; trainer_returncode is in completion.json"
        self.save()

    def read_supervisor(self):
        path = self.supervision / "state.json"
        return read_json(path) if path.exists() else {}

    def read_completion(self):
        receipt = read_json(self.directory / "completion.json")
        if (not isinstance(receipt, dict) or type(receipt.get("version")) is not int or receipt["version"] != 1
                or receipt.get("run") != self.config["run"]):
            raise ValueError("Trainer completion receipt has an invalid version or run identity")
        for key in ("started_at", "finished_at"):
            value = receipt.get(key)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                raise ValueError("Trainer completion receipt must identify finite start/finish times")
        code = receipt.get("returncode")
        if type(code) is not int:
            if code is not None or not isinstance(receipt.get("error"), str) or not receipt["error"]:
                raise ValueError("Trainer completion receipt needs an actual integer returncode or an explicit startup error")
        elif type(receipt.get("trainer_pid")) is not int or receipt["trainer_pid"] <= 0:
            raise ValueError("Trainer completion receipt must identify the actual trainer process")
        return receipt

    def supervisor_command(self, once=False):
        return [sys.executable, str(SCRIPTS / "supervise.py"), *self.supervisor_args,
                *(["--once"] if once else [])]

    def wait_preflight(self, process):
        while process.poll() is None:
            time.sleep(self.config["poll_seconds"])
        self.child_finished("discovery")
        state = self.read_supervisor()
        self.save(supervision_status=state.get("status"))
        return process.returncode == 0 and state.get("discovery_complete") and state.get("status") == "watching"

    def monitor(self, trainer, supervisor):
        trainer_started = time.monotonic()
        final_started = None
        while True:
            trainer_code, supervisor_code = trainer.poll(), supervisor.poll()
            marker = self.directory / "completion.json"
            if final_started is None and marker.exists():
                receipt = self.read_completion()
                self.save("finalizing", trainer_returncode=receipt["returncode"], trainer=receipt)
                final_started = time.monotonic()
            if final_started is not None:
                # The durable receipt is written before the wrapper exits. A
                # fast final review may finish inside that window; await both
                # processes rather than treating it as early supervision loss.
                if trainer_code is not None:
                    self.child_finished("trainer")
                if trainer_code is not None and supervisor_code is not None:
                    self.child_finished("supervisor")
                    state = self.read_supervisor()
                    self.save(supervisor_returncode=supervisor_code, supervision_status=state.get("status"))
                    if self.state["trainer_returncode"] != 0:
                        self.save("trainer_failed")
                        return 2
                    if trainer_code != 0:
                        self.save("trainer_wrapper_failed")
                        return 2
                    if supervisor_code == 0 and state.get("status") == "completed":
                        self.save("completed")
                        return 0
                    self.save("supervision_" + str(state.get("status") or "failed"))
                    return 2
                if time.monotonic() - final_started >= self.config["final_timeout_seconds"]:
                    self.save("final_timeout")
                    return 2
            elif trainer_code is not None:
                self.child_finished("trainer")
                self.save("trainer_completion_missing", trainer_returncode=None,
                          error="Trainer wrapper exited without a durable completion receipt")
                return 2
            elif supervisor_code is not None:
                self.child_finished("supervisor")
                state = self.read_supervisor()
                self.save("supervision_" + str(state.get("status") or "failed"),
                          supervisor_returncode=supervisor_code, supervision_status=state.get("status"),
                          error="Supervision ended before the owned trainer; stopping that trainer")
                return 2
            elif time.monotonic() - trainer_started >= self.config["trainer_timeout_seconds"]:
                self.save("trainer_timeout")
                stop_group(trainer)
                # Permit a read-only final pass after the wrapper records the
                # real exit, while retaining the timeout as the overall result.
                deadline = time.monotonic() + self.config["final_timeout_seconds"]
                while supervisor.poll() is None and time.monotonic() < deadline:
                    time.sleep(self.config["poll_seconds"])
                state = self.read_supervisor()
                self.save("trainer_timeout", supervision_status=state.get("status"))
                return 2
            time.sleep(self.config["poll_seconds"])

    def run(self, detached=False):
        check_fresh(self.config, self.directory, self.parsed)
        self.directory.mkdir(parents=True, exist_ok=False)
        self.guard = (self.directory / "runtime.lock").open("a+")
        fcntl.flock(self.guard, fcntl.LOCK_EX | fcntl.LOCK_NB)
        try:
            self.state["owner"]["mode"] = "detached" if detached else "foreground"
            self.detached = detached
            for fd, name in ((1, "runtime.stdout"), (2, "runtime.stderr")):
                with (self.directory / name).open("ab", buffering=0) as output:
                    if detached:
                        os.dup2(output.fileno(), fd)
            atomic_json(self.directory / "launch.json", self.config)
            atomic_json(self.directory / "contract.json", self.config["contract"])
            self.save("discovery")
            discovery = self.spawn("discovery", self.supervisor_command(once=True))
            if not self.wait_preflight(discovery):
                self.save("discovery_failed", error="Read-only discovery did not authorize continuation; trainer was not started")
                return 2
            # Recheck the path following discovery; no unrelated training log
            # may have appeared while the model was inspecting the checkout.
            log = resolve(self.root, self.parsed.log)
            if log.exists():
                raise ValueError("Planned log appeared during discovery; refusing to launch a trainer")
            log.parent.mkdir(parents=True, exist_ok=True)
            trainer = self.spawn("trainer", [sys.executable, str(Path(__file__).resolve()),
                                 "--_trainer", str(self.directory)])
            supervisor = self.spawn("supervisor", self.supervisor_command())
            self.save("training")
            code = self.monitor(trainer, supervisor)
            return code
        except KeyboardInterrupt:
            self.save("interrupted", error="Runtime interrupted; stopping only its owned children")
            return 130
        except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
            self.save("runtime_failed", error=f"{type(error).__name__}: {error}")
            return 2
        finally:
            for name, process in reversed(list(self.children.items())):
                stop_group(process)
                self.child_finished(name)
            marker = self.directory / "completion.json"
            if marker.exists():
                receipt = read_json(marker)
                self.state.update(trainer_returncode=receipt.get("returncode"), trainer=receipt)
            if "supervisor" in self.children:
                self.state["supervisor_returncode"] = self.children["supervisor"].returncode
                self.state["supervision_status"] = self.read_supervisor().get("status")
            self.state["owner"]["running"] = False
            self.save(finished_at=time.time())
            for handle in self.handles:
                handle.close()
            self.guard.close()


def run_trainer(directory):
    """The managed wrapper writes a receipt before the parent can observe exit."""
    directory = Path(directory)
    config = read_json(directory / "launch.json")
    stopping = []
    def signal_requested(signum, frame):
        stopping.append(signum)
    signal.signal(signal.SIGTERM, signal_requested)
    signal.signal(signal.SIGINT, signal_requested)
    started = time.time()
    process = None
    try:
        process = subprocess.Popen(config["trainer_command"], cwd=config["root"], stdin=subprocess.DEVNULL)
        atomic_json(directory / "trainer-process.json", {"pid": process.pid, "start_token": pid_start(process.pid),
                                                       "started_at": started})
        stop_at = None
        while process.poll() is None:
            if stopping:
                if stop_at is None:
                    try:
                        process.terminate()
                    except ProcessLookupError:
                        pass
                    stop_at = time.monotonic()
                elif time.monotonic() - stop_at >= 2:
                    try:
                        process.kill()
                    except ProcessLookupError:
                        pass
            time.sleep(min(config["poll_seconds"], 0.1))
        code = process.returncode
        atomic_json(directory / "completion.json", {"version": 1, "run": config["run"],
                    "returncode": code, "started_at": started, "finished_at": time.time(),
                    "trainer_pid": process.pid, "stop_signal": stopping[0] if stopping else None})
        return 0 if code == 0 else 2
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        atomic_json(directory / "completion.json", {"version": 1, "run": config["run"],
                    "returncode": None, "started_at": started, "finished_at": time.time(),
                    "error": f"{type(error).__name__}: {error}"})
        return 2


def detach(config_path, config, directory, parsed):
    check_fresh(config, directory, parsed)
    # The child alone creates the run directory. Parent-side launch logs live
    # in the existing reports/runtime parent until the verified child owns it.
    directory.parent.mkdir(parents=True, exist_ok=True)
    import tempfile
    with tempfile.TemporaryFile() as startup:
        process = subprocess.Popen([sys.executable, str(Path(__file__).resolve()), "--config", str(config_path),
                                    "--_detached"], stdin=subprocess.DEVNULL, stdout=startup, stderr=startup,
                                   start_new_session=True, close_fds=True)
        confirmed = False
        try:
            deadline = time.monotonic() + 10
            while time.monotonic() < deadline:
                state_path = directory / "state.json"
                if state_path.exists():
                    state = read_json(state_path)
                    owner = state.get("owner", {})
                    identity_matches = owner.get("pid") == process.pid and owner.get("start_token") == pid_start(process.pid)
                    if identity_matches and owner.get("running") and process.poll() is None and run_lock_held(directory):
                        confirmed = True
                        print(json.dumps({"status": "started", "phase": state["status"], "owner": owner,
                                          "state": str(state_path)}, ensure_ascii=False), flush=True)
                        return 0
                    if not owner.get("running"):
                        process.wait(timeout=10)
                        print(json.dumps({"status": state["status"], "state": str(state_path)}), flush=True)
                        return process.returncode
                if process.poll() is not None:
                    startup.seek(0)
                    raise ValueError("Detached runtime exited before ownership handshake: " + startup.read().decode(errors="replace"))
                time.sleep(0.05)
            raise ValueError("Detached runtime failed its live-owner handshake")
        finally:
            if not confirmed:
                stop_group(process)


def main():
    if sys.argv[1:2] == ["--_trainer"]:
        return run_trainer(sys.argv[2])
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--config", required=True, help="Version 1 launch JSON generated from the experiment request")
    parser.add_argument("--detach", action="store_true", help="Run the same owner in a new session, without installing a service")
    parser.add_argument("--_detached", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args()
    def terminate(signum, frame):
        raise KeyboardInterrupt
    signal.signal(signal.SIGTERM, terminate)
    try:
        config_path = Path(args.config).expanduser().resolve()
        config, directory, parsed, flags = normalized_config(config_path)
        if args.detach:
            return detach(config_path, config, directory, parsed)
        return Runtime(config, directory, parsed, flags).run(detached=args._detached)
    except KeyboardInterrupt:
        return 130
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(f"[RUNTIME] {error}", file=sys.stderr, flush=True)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
